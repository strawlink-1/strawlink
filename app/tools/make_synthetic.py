"""Synthetic machines, plants, phones and combine bookings → config/synthetic.yaml.

    python app/tools/make_synthetic.py

Everything here is invented for the demo and tagged synthetic: true. Machine rates
and plant capacities are ASSUMPTIONS to be replaced with cited figures. Real team
phone numbers for demo fields are NOT written here — they come from the SSM
parameter /strawlink/demo_phone_map at runtime.
"""

from __future__ import annotations

import json
import math
from datetime import date, timedelta
from pathlib import Path

import numpy as np
import yaml

ROOT = Path(__file__).resolve().parents[2]

# ASSUMPTION — cite: typical rates in Punjab extension material; replace with sourced values.
MACHINE_TYPES = {
    "baler_set": {"count": 3, "rate_t_per_hr": 3.5, "hours_per_day": 9,
                  "note": "rake + square baler; ASSUMPTION — cite"},
    "seeder": {"count": 3, "rate_t_per_hr": 2.7, "hours_per_day": 9,
               "note": "Super Seeder ~0.45 ha/h × 6 t/ha straw; ASSUMPTION — cite"},
    "truck": {"count": 3, "rate_t_per_hr": 10.0, "hours_per_day": 10,
              "note": "tractor-trolley haul; ASSUMPTION — cite"},
}
# (name, kind, dx_km east, dy_km north from block centre, weekly t, depot t, fill t) — all SYNTHETIC
PLANTS = [
    ("P01", "Biomass boiler (synthetic)", 14, -6, 350, 500, 120),
    ("P02", "Pellet plant (synthetic)", -18, 9, 200, 300, 160),
    ("P03", "CBG plant (synthetic)", 6, 24, 250, 400, 60),
]


def offset(lon, lat, dx, dy):
    return [round(lon + dx / (111.32 * math.cos(math.radians(lat))), 6), round(lat + dy / 110.574, 6)]


def main() -> None:
    params = yaml.safe_load((ROOT / "config" / "params.yaml").read_text())
    rng = np.random.default_rng(int(params["random_seed"]))
    fields = json.loads((ROOT / "data" / "fields" / "fields.geojson").read_text())["features"]
    villages = json.loads((ROOT / "data" / "fields" / "villages.geojson").read_text())["features"]
    vil = sorted(((v["properties"]["village_id"], v["properties"]["name"], v["geometry"]["coordinates"]) for v in villages))
    lon = float(np.mean([c[0] for _, _, c in vil]))
    lat = float(np.mean([c[1] for _, _, c in vil]))

    machines = []
    prefix = {"baler_set": "BA", "seeder": "SE", "truck": "TR"}
    for t, spec in MACHINE_TYPES.items():
        for k in range(spec["count"]):
            vid, vname, c = vil[k % len(vil)]
            machines.append({
                "machine_id": f"{prefix[t]}{k + 1:02d}", "type": t, "base": [round(c[0], 6), round(c[1], 6)],
                "rate_t_per_hr": spec["rate_t_per_hr"], "hours_per_day": spec["hours_per_day"],
                "available": True, "village_id": vid, "village_name": vname,
                "operator_name": f"Operator {prefix[t]}{k + 1} (synthetic)",
                "phone": f"+910000{len(machines) + 1:06d}", "synthetic": True,
            })
    plants = [{"plant_id": pid, "name": name, "location": offset(lon, lat, dx, dy),
               "weekly_capacity_t": w, "depot_capacity_t": d, "fill_t": f, "synthetic": True}
              for pid, name, dx, dy, w, d, f in PLANTS]
    phones = {f["properties"]["field_id"]: f"+919{i + 1:09d}" for i, f in enumerate(fields)}
    ids = sorted(phones)
    booked = sorted(rng.choice(ids, size=max(1, round(0.15 * len(ids))), replace=False).tolist())
    bookings = [{"field_id": fid, "combine_booked_on": (date(2026, 10, 15) + timedelta(days=int(rng.integers(0, 21)))).isoformat(),
                 "synthetic": True} for fid in booked]

    doc = {
        "version": "0.1",
        "synthetic": True,
        "note": "All entries are invented for the demo. Rates/capacities are ASSUMPTIONS pending citations.",
        "machine_type_notes": {t: s["note"] for t, s in MACHINE_TYPES.items()},
        "machines": machines,
        "plants": plants,
        "farmer_phones": {"synthetic": True, "note": "fake numbers (+919…); demo numbers come from SSM", "by_field": phones},
        "combine_bookings": bookings,
    }
    out = ROOT / "config" / "synthetic.yaml"
    out.write_text("# GENERATED by app/tools/make_synthetic.py — synthetic demo inputs, not real data.\n"
                   + yaml.safe_dump(doc, sort_keys=False, allow_unicode=True))
    print(json.dumps({"machines": len(machines), "plants": len(plants), "phones": len(phones), "bookings": len(bookings)}))


if __name__ == "__main__":
    main()
